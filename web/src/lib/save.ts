/**
 * 保存请求的结果（前端内部契约）。
 *
 * 保存正文/标签的回调 prop 用这个类型返回值，而不是 `boolean` ——
 * `boolean` 分不出「请求发出去了但失败了」和「压根没发出去（被在飞保护挡下了）」，
 * 而这两种情况要做的后续动作完全不同（见 {@link SaveOutcome}）。
 */

/**
 * 保存的结果。
 *
 * - `'saved'`：存好了。
 * - `'failed'`：请求发出去了、失败了（失败原因由上层弹提示）。
 * - `'busy'`：**请求压根没发出去** —— 被同一条目上的在飞保护挡下了。
 *
 * `'busy'` 必须能跟 `'failed'` 分开：被挡下的那一次，调用方要把它**重新入队**，
 * 等在飞结束再补存。要是都当成 `false`，那次改动就静默没了 ——
 * 界面上还显示着新标签、服务端没有、也没有任何提示。
 */
export type SaveOutcome = 'saved' | 'failed' | 'busy';

/**
 * 保存请求的附加选项。
 */
export interface SaveOptions {
  /**
   * 失败时不弹错误提示。
   *
   * 给「用户没有主动操作」的自动保存用：比如捡回上次没存上的标签后自动补存 ——
   * 用户只是打开编辑器看看、没改任何东西，弹一句「保存标签失败」只会让人莫名其妙。
   */
  silent: boolean;
}
